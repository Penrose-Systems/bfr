#!/bin/sh
# Compiles the test shaders to SPIR-V and writes them into spirv.h as arrays
# of bytes, as a caller hands code to BFR, so the tests need no compiler. Run
# after changing a shader; the header is checked in.
set -e
cd "$(dirname "$0")"
{
    echo "// Generated by compile.sh from the shaders beside it. Do not edit."
    echo "#pragma once"
    echo
    echo "#include <array>"
    echo "#include <cstdint>"
    echo
    echo "namespace bfr::test::spirv {"
    for stage in comp vert frag; do
        glslangValidator -V --target-env vulkan1.3 -o "bindless.$stage.spv" "bindless.$stage" > /dev/null
        echo
        echo "/// bindless.$stage, as SPIR-V bytes."
        printf "inline constexpr std::array<std::uint8_t, %s> kBindless%s{\n" \
            "$(stat -c %s "bindless.$stage.spv")" \
            "$(echo "$stage" | sed 's/^./\U&/')"
        od -An -v -t u1 -w24 "bindless.$stage.spv" | sed 's/^ *//; s/  */, /g; s/^/    /; s/$/,/'
        echo "};"
        rm "bindless.$stage.spv"
    done
    echo
    echo "} // namespace bfr::test::spirv"
} > spirv.h
