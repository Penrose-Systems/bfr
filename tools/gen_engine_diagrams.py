#!/usr/bin/env python3
"""Generate the engine diagrams from docs/engine_architecture.toml.

The TOML module list is the source of truth for the engine's structure. This
tool turns it into the Mermaid diagram engine_architecture.mmd beside it (one
row of clients over the engine, a grid of modules in file order) and the module
list between the markers in architecture.md.

It opens on GitHub, in VS Code, at https://mermaid.live and imports into
draw.io. Edit the TOML, never the .mmd file, then run:

    python3 tools/gen_engine_diagrams.py           # regenerate
    python3 tools/gen_engine_diagrams.py --check   # fail if out of date (CI)
"""

from __future__ import annotations

import argparse
import pathlib
import sys
import tomllib

REPO_ROOT = pathlib.Path(__file__).resolve().parent.parent
DEFAULT_SOURCE = REPO_ROOT / "docs" / "engine_architecture.toml"
GENERATED = "Generated by tools/gen_engine_diagrams.py from engine_architecture.toml. Do not edit."
CLIENTS_ID = "clients"
CLIENTS_NAME = "Clients"
CLIENTS_NOTE = "outside the engine, through the live endpoint only"
ENGINE_ID = "engine"
ENGINE_NAME = "Engine"
# Title cell plus modules per row of the engine grid.
ENGINE_COLUMNS = 6
MAP_OPEN = "<!-- modules -->"
MAP_CLOSE = "<!-- /modules -->"
# Structure only: module design lives in the module docs.
FILE_KEYS = {"client", "module"}
ITEM_KEYS = {"id", "name"}

CLASS_DEFS = (
    "  classDef engine fill:#e6ecfb,stroke:#2c4fb8,stroke-width:1.5px,color:#1b2230\n"
    "  classDef client fill:#f2f2f2,stroke:#5a6577,stroke-dasharray:4 3,color:#1b2230\n"
)


def _reject_unknown_keys(path: pathlib.Path, owner: str, table: dict, allowed: set[str]) -> None:
    unknown = sorted(set(table) - allowed)
    if unknown:
        raise ValueError(f"{path}: {owner} has unknown keys {unknown}; expected only {sorted(allowed)}")


def _check_items(path: pathlib.Path, kind: str, items: list[dict], seen: set[str]) -> None:
    for item in items:
        item_id = item.get("id")
        _reject_unknown_keys(path, f"{kind} '{item_id}'", item, ITEM_KEYS)
        if not item_id or not item.get("name"):
            raise ValueError(f"{path}: every {kind} needs an id and a name")
        if item_id in seen:
            raise ValueError(f"{path}: id '{item_id}' is used more than once")
        seen.add(item_id)


def load_model(path: pathlib.Path) -> dict:
    """Read and validate the clients and the module list. Order in the file is order in the diagram."""
    with path.open("rb") as handle:
        model = tomllib.load(handle)
    _reject_unknown_keys(path, "the file", model, FILE_KEYS)
    seen: set[str] = set()
    _check_items(path, "client", model.setdefault("client", []), seen)
    _check_items(path, "module", model.setdefault("module", []), seen)
    if not model["module"]:
        raise ValueError(f"{path}: the file has no modules")
    return model


def module_list(model: dict, docs: pathlib.Path) -> str:
    """One line per module, linking its doc under docs/modules/ when that file exists."""
    lines = []
    for module in model["module"]:
        doc = f"modules/{module['id']}.md"
        name = f"[{module['name']}]({doc})" if (docs / doc).is_file() else module["name"]
        lines.append(f"- {name}\n")
    return "".join(lines)


def _spliced_map(path: pathlib.Path, listed: str) -> str:
    """The map with the block between its markers replaced by the module list."""
    if not path.is_file():
        raise ValueError(f"{path}: missing; it holds the module list between {MAP_OPEN} and {MAP_CLOSE}")
    text = path.read_text(encoding="utf-8")
    start = text.find(MAP_OPEN)
    end = text.find(MAP_CLOSE)
    if start < 0 or end < start:
        raise ValueError(f"{path}: needs {MAP_OPEN} and {MAP_CLOSE} around the module list")
    return text[: start + len(MAP_OPEN)] + "\n" + listed + text[end:]


def _classes(items: list[dict], kind: str) -> str:
    return "".join(f"  class {item['id']} {kind}\n" for item in items)


def _blocks(model: dict) -> list[tuple[str, str, int, list[dict], str]]:
    """Each diagram block as (id, title, columns, items, class): the clients, if any, then the engine."""
    blocks = [(ENGINE_ID, ENGINE_NAME, ENGINE_COLUMNS, model["module"], "engine")]
    if model["client"]:
        # The title starts its row, so the row is one cell wider than its items.
        title = f"{CLIENTS_NAME}<br/>{CLIENTS_NOTE}"
        blocks.insert(0, (CLIENTS_ID, title, len(model["client"]) + 1, model["client"], "client"))
    return blocks


def architecture_mermaid(model: dict) -> str:
    blocks = _blocks(model)
    out = ["block-beta\n", f"%% {GENERATED}\n", "  columns 1\n"]
    for block_id, title, columns, items, _ in blocks:
        out.append(f"  block:{block_id}:1\n    columns {columns}\n")
        cells = [f'{block_id}_title["{title}"]'] + [f'{item["id"]}["{item["name"]}"]' for item in items]
        out.append("    " + " ".join(cells) + "\n")
        out.append("  end\n")
    out.append(CLASS_DEFS)
    out.append("  classDef title fill:#ffffff,stroke:#ffffff,color:#1b2230,font-weight:bold\n")
    for _, _, _, items, kind in blocks:
        out.append(_classes(items, kind))
    out.append("  class " + ",".join(f"{block_id}_title" for block_id, _, _, _, _ in blocks) + " title\n")
    for block_id, _, _, _, _ in blocks:
        out.append(f"  style {block_id} fill:#f6f7f9,stroke:#b8c0cc\n")
    return "".join(out)


def render_all(source: pathlib.Path, check: bool) -> list[str]:
    """Write the diagram beside the source, or with check=True list it if stale."""
    model = load_model(source)
    map_path = source.with_name("architecture.md")
    targets = {
        source.with_name("engine_architecture.mmd"): architecture_mermaid(model),
        map_path: _spliced_map(map_path, module_list(model, source.parent)),
    }
    stale: list[str] = []
    for path, text in targets.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        if check:
            stale.append(path.name)
        else:
            path.write_text(text, encoding="utf-8")
    return stale


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--source", type=pathlib.Path, default=DEFAULT_SOURCE)
    parser.add_argument("--check", action="store_true", help="fail if a generated diagram is out of date")
    args = parser.parse_args()
    try:
        stale = render_all(args.source, args.check)
    except (OSError, ValueError, tomllib.TOMLDecodeError) as error:
        print(f"gen_engine_diagrams: {error}", file=sys.stderr)
        return 2
    if stale:
        print("gen_engine_diagrams: out of date: " + ", ".join(stale), file=sys.stderr)
        print("Run: python3 tools/gen_engine_diagrams.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
