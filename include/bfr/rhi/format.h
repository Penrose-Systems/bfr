/// How a window's display reads presented values. The values are the C API's.
enum class ColorSpace : std::uint8_t {
    Srgb = 1,
    SrgbExtendedLinear,
    SrgbExtended,
    DisplayP3,
    DisplayP3Linear,
    DciP3,
    Bt709,
    Bt709Linear,
    Bt2020Linear,
    Hdr10Pq,
    Hdr10Hlg,
    DolbyVision,
    AdobeRgb,
    AdobeRgbLinear,
    PassThrough,
    DisplayNative,
};

/// How a window's display is turned. The values are the C API's.
enum class SurfaceRotation : std::uint8_t {
    None,
    Rotate90,
    Rotate180,
    Rotate270,
    Other,
};

